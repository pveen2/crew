// Translates one engine-neutral agent folder into the files a CLI reads in its
// working folder. Every engine gets the same two things:
//
//   AGENTS.md                         rules + instructions + setup + memory
//   .agents/skills/<name>/SKILL.md    the agent's skills (own and shared)
//
// Codex and Grok read both natively. Claude Code reads AGENTS.md natively and
// gets .agents/ as a plugin folder (--plugin-dir, see engines/claude.ts).
// Antigravity reads both natively (and its MCP servers from .agents/mcp_config.json).
// Plus context/brand/ (read-only copy) and, for draft permissions, drafts/. The
// conductor adds attachments/ (the thread's images, read-only) before each turn.

import { chmodSync, cpSync, existsSync, lstatSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import type { Engine } from '@crew/protocol';
import { subagentToolName, type LoadedAgent, type LoadedCrew } from '@crew/sdk/load';

export const SKILLS_DIR = '.agents/skills';

export interface MemoryRecall {
  name: string;
  description: string;
  entries: Array<{ id: string; text: string }>;
}

export interface TranslateOptions {
  crew: LoadedCrew;
  agent: LoadedAgent;
  engine: Engine;
  workdir: string;
  /** The lead in its own thread: offer one tool per subagent. */
  canDelegate: boolean;
  /** Current memory entries, recalled into AGENTS.md. */
  memories?: MemoryRecall[];
  /** Model comparison run (pnpm crew try): no colleagues and no Crew tools. */
  comparison?: boolean;
  /** Specialists switched off in this thread: no tool, and the lead is told. */
  benched?: string[];
}

export interface CrewToolInfo {
  name: string;
  description: string;
}

const GENERATED_NOTE = '<!-- Generated by Crew from packages/crew. Do not edit: this file is rewritten on every turn. -->';

/** The Crew tools (MCP server `crew`) an agent gets, besides its own tools/*.ts. */
export function crewTools(crew: LoadedCrew, agent: LoadedAgent, canDelegate: boolean, benched: string[] = []): CrewToolInfo[] {
  const tools: CrewToolInfo[] = [];
  if (canDelegate) {
    for (const sub of Object.values(crew.agents).filter((a) => !a.isLead && !benched.includes(a.name))) {
      tools.push({ name: subagentToolName(sub.name), description: `Call the ${sub.label}: ${sub.description}` });
    }
  }
  if (canDelegate) {
    tools.push({ name: 'rename_thread', description: 'Give the thread a clearer 3–6 word title when the current one is vague or wrong.' });
  }
  tools.push({ name: 'ask_owner', description: 'Ask the owner one question only they can answer, with clickable options when there are a few choices, then end your turn.' });
  tools.push({
    name: 'show_preview',
    description: 'Show a document to the owner: an artifactId, or short content. Use html (styled by Crew) for anything visual or with images.',
  });
  if (!agent.isLead) tools.push({ name: 'save_artifact', description: 'Save long work and get an id to hand back.' });
  tools.push({ name: 'read_artifact', description: 'Read an artifact by id.' });
  tools.push({ name: 'list_docs', description: "List this thread's docs shown to the owner, with ids and which are approved." });
  if (agent.permissions === 'code') {
    if (crew.config.code?.theme) tools.push({ name: 'theme_preview', description: "Push your checkout's theme to the store's development theme and get the preview and editor links." });
    tools.push({ name: 'code_review', description: 'Have a reviewer from another vendor check your changes. Required before every open_pull_request, on exactly the changes you open it with.' });
    tools.push({ name: 'open_pull_request', description: 'Commit your changes, push your branch and open (or update) its pull request. The owner reviews and merges it.' });
  }
  for (const m of agent.memories) {
    tools.push({ name: `${m.name}__save_memory`, description: `Add an entry to your ${m.name} memory.` });
    tools.push({ name: `${m.name}__remove_memory`, description: `Remove an entry from your ${m.name} memory by id.` });
  }
  for (const t of agent.tools) tools.push({ name: t.name, description: t.description });
  return tools;
}

function makeReadOnly(path: string): void {
  for (const entry of readdirSync(path, { withFileTypes: true })) {
    const p = join(path, entry.name);
    if (entry.isDirectory()) makeReadOnly(p);
    else chmodSync(p, 0o444);
  }
}

function resetDir(dir: string): void {
  // Files may be read-only from a previous turn; the folder itself is writable.
  if (existsSync(dir)) rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
}

function writeFresh(file: string, content: string): void {
  if (existsSync(file)) rmSync(file, { force: true });
  writeFileSync(file, content);
}

export function instructionsMarkdown(opts: TranslateOptions): string {
  const { crew, agent, canDelegate, comparison } = opts;
  const parts: string[] = [GENERATED_NOTE, '', `# You are the ${agent.label} of Crew`, ''];

  parts.push(crew.rules, '', '---', '', agent.instructions, '');

  parts.push('## Your setup', '');
  parts.push(
    `- Permissions: **${agent.permissions}**.` +
      (agent.permissions === 'draft'
        ? ' You may create and edit files in `drafts/` only. Nothing else.'
        : agent.permissions === 'code'
          ? ' You work in `repo/`, your own clone of the team\'s code repo, on your own branch.'
          : ' You may read, but not create or change, files.'),
  );
  if (agent.permissions === 'code') {
    const code = crew.config.code;
    parts.push(
      `- \`repo/\` is ${code?.repo ?? 'the code repo'}, branched from \`${code?.base ?? 'main'}\` at the start of this thread; it stays yours for the whole thread. ` +
        'Edit and create files only inside it. Read its AGENTS.md / README files before you change anything, and follow them.',
      '- Your shell runs in a sandbox: it can change files only in `repo/`, has no network and no credentials. Run checks, tests and scripts there. ' +
        'Do not install packages or call the internet; ask the owner when something needs that.',
      '- You do not commit, push or merge yourself. `open_pull_request` commits your work, pushes the branch and opens or updates the pull request; ' +
        'the owner reviews and merges it. Never try to change the live theme or the base branch another way.',
      '- Before `open_pull_request`: run the repo\'s checks, look at your change with `theme_preview` when it shows on the store, and run `code_review`; fix what it finds or say why not. ' +
        '`open_pull_request` refuses changes `code_review` has not seen, so review again after every change, and the review goes on the pull request word for word. ' +
        'Put the preview link, what you checked and what the owner should test in the pull request body.',
    );
  }
  if (comparison) {
    parts.push('- This is a model comparison run. You have no colleagues and no Crew tools.');
    parts.push('  Answer the request directly and completely in your reply.');
  } else {
    parts.push('- Crew tools (MCP server `crew`):');
    for (const t of crewTools(crew, agent, canDelegate, opts.benched)) parts.push(`  - \`${t.name}\`: ${t.description}`);
    if (canDelegate) {
      parts.push(
        '- When the owner names a specialist with @ (e.g. `@developer fix the header`), they want that specialist on it: ' +
          'call its tool with a full brief straight away, without asking first, then report back here with what it did. ' +
          'If that specialist is switched off for this thread, say so and do it yourself.',
      );
    }
    if (agent.isLead && !canDelegate) parts.push('  - You cannot call specialists in this thread. Do the work yourself or say what is missing.');
    const off = canDelegate ? (opts.benched ?? []).map((n) => crew.agents[n]).filter((a) => a && !a.isLead) : [];
    if (off.length) {
      parts.push(
        `- Switched off by the owner for this thread: ${off.map((a) => `the ${a!.label} (@${a!.name})`).join(', ')}.` +
          ' You cannot call them here, whatever your instructions say about them. Do their part yourself or with the specialists you have, and do not ask the owner to switch them back on.',
      );
    }
  }
  const conns = Object.entries(agent.connections);
  if (conns.length) {
    parts.push('- Connections:');
    for (const [name, c] of conns) parts.push(`  - \`${name}\` (${c.tools.allow.map((t) => `\`${t}\``).join(', ')}): ${c.description}`);
  }
  if (agent.skills.length) {
    parts.push(`- Skills (in \`${SKILLS_DIR}/\`), read one when its description fits:`);
    for (const s of agent.skills) parts.push(`  - \`${s.name}\`: ${s.description}`);
  }
  parts.push('');

  if (!comparison && opts.memories?.length) {
    for (const m of opts.memories) {
      parts.push(`## Your memory: ${m.name}`, '', m.description, '');
      if (m.entries.length) for (const e of m.entries) parts.push(`- [${e.id}] ${e.text}`);
      else parts.push('_Empty._');
      parts.push('');
    }
    if (agent.isLead) parts.push('Specialists do not see your memory. Put the preferences that matter for a task in the brief.', '');
  }

  return parts.join('\n');
}

/** Write the files into the session folder. Returns the paths written. */
export function translateAgent(opts: TranslateOptions): string[] {
  const { crew, agent, workdir } = opts;
  const written: string[] = [];
  mkdirSync(workdir, { recursive: true });
  // An agent that can write its own folder (a code agent's shell) could swap these for symlinks
  // to send the writes and deletes below somewhere else. Remove such links first.
  for (const p of ['AGENTS.md', '.agents', SKILLS_DIR, 'context', 'context/brand', 'drafts', 'attachments']) {
    try {
      if (lstatSync(join(workdir, p)).isSymbolicLink()) rmSync(join(workdir, p), { force: true });
    } catch {
      // Not there.
    }
  }

  // Sessions started before the eve layout may still hold engine-specific files; a
  // resumed CLI must not read stale instructions or skills from them.
  for (const legacy of ['CLAUDE.md', '.claude/skills', '.claude/agents', '.grok/skills', 'context/team.md']) {
    rmSync(join(workdir, legacy), { recursive: true, force: true });
  }

  const instrFile = join(workdir, 'AGENTS.md');
  writeFresh(instrFile, instructionsMarkdown(opts));
  written.push(instrFile);

  const skillsDir = join(workdir, SKILLS_DIR);
  resetDir(skillsDir);
  for (const s of agent.skills) {
    const dest = join(skillsDir, s.name);
    cpSync(s.dir, dest, { recursive: true });
    written.push(join(dest, 'SKILL.md'));
  }

  const brandDest = join(workdir, 'context', 'brand');
  resetDir(brandDest);
  let copied = false;
  for (const { from, to } of crew.brand) {
    if (!existsSync(from)) continue;
    const dest = join(brandDest, to);
    mkdirSync(statSync(from).isDirectory() ? dest : dirname(dest), { recursive: true });
    cpSync(from, dest, { recursive: true });
    copied = true;
  }
  if (copied) {
    makeReadOnly(brandDest);
    written.push(brandDest + '/');
  }

  if (agent.permissions === 'draft') mkdirSync(join(workdir, 'drafts'), { recursive: true });

  return written;
}
